const fw = require('./.build/firewall.cjs'); const { T, createAdminClient } = require('./fakeAdmin.cjs'); const db = createAdminClient()
let ok = 0, ko = 0; const check = (c, m) => { c ? ok++ : ko++; console.log((c ? 'OK   ' : 'ECHEC') + ' ' + m) }
const P = 'pro-A', Q = 'pro-B'
T.provider_profiles.push({ id: P, is_active: true, payments_suspended_at: null, sepa_mandate_status: 'active' }, { id: Q, is_active: true, payments_suspended_at: null, sepa_mandate_status: 'active' })
;(async () => {
  console.log('-- Prestataire A : mandat révoqué sans dette')
  await fw.recordIncident({ providerId: P, kind: 'mandate_revoked', psp: 'test' })
  const a = () => T.provider_profiles.find(x => x.id === P)
  check(a().sepa_mandate_status === 'revoked', 'statut du mandat = révoqué')
  check(T.payment_alerts.filter(x => x.provider_id === P).length === 1, 'PING reçoit une alerte')
  check(!a().payments_suspended_at, 'pas de suspension tant que rien n’est dû')
  console.log('-- Prélèvement de commission rejeté : 30 €')
  await fw.recordIncident({ providerId: P, kind: 'debit_rejected', amountCents: 3000, transactionId: 'tx1', psp: 'test' })
  check(await fw.openDebtCents(db, P) === 3000, 'dette ouverte = 30 €')
  check(!a().payments_suspended_at, 'sous le plafond de 50 € : pas encore suspendu')
  console.log('-- Opposition du client après versement : 25 € (total 55 € > 50 €)')
  await fw.recordIncident({ providerId: P, kind: 'chargeback', amountCents: 2500, transactionId: 'tx2', psp: 'test' })
  check(!!a().payments_suspended_at && a().is_active === false, 'compte suspendu et retiré de la carte')
  check(/55,00 €/.test(T.provider_private.find(x => x.id === P)?.suspension_reason || ''), 'motif enregistré : ' + T.provider_private.find(x => x.id === P)?.suspension_reason)
  check(await fw.isSuspended(db, P) === true, 'le versement voit la suspension (aucun virement)')
  console.log('-- Compensation sur un versement de 40 €')
  const plan = await fw.planNetting(db, P, 4000)
  check(plan.netPayoutCents === 0 && plan.recoveredCents === 4000, `versement net 0 €, retenu 40 € (net ${plan.netPayoutCents}, retenu ${plan.recoveredCents})`)
  await fw.applyNetting(db, P, 'tx3', plan.plan)
  check(await fw.openDebtCents(db, P) === 1500, 'reste dû 15 €')
  check(T.commission_debts.filter(d => d.provider_id === P && d.status === 'recovered').reduce((s, d) => s + d.amount_cents, 0) === 4000, '40 € tracés comme récupérés')
  console.log('-- Versement de 100 € : solde la dette, verse le reste')
  const plan2 = await fw.planNetting(db, P, 10000)
  check(plan2.netPayoutCents === 8500 && plan2.recoveredCents === 1500, `net 85 €, retenu 15 € (${plan2.netPayoutCents}/${plan2.recoveredCents})`)
  await fw.applyNetting(db, P, 'tx4', plan2.plan)
  check(await fw.openDebtCents(db, P) === 0, 'plus aucune dette')
  console.log('-- Levée de la suspension par l’admin')
  await fw.unsuspendProvider(P, 'admin')
  check(!a().payments_suspended_at, 'suspension levée')
  console.log('-- Prestataire B : 10 € rejetés puis mandat révoqué')
  await fw.recordIncident({ providerId: Q, kind: 'debit_rejected', amountCents: 1000, psp: 'test' })
  check(!T.provider_profiles.find(x => x.id === Q).payments_suspended_at, '10 € dus : pas suspendu')
  await fw.recordIncident({ providerId: Q, kind: 'mandate_revoked', psp: 'test' })
  check(!!T.provider_profiles.find(x => x.id === Q).payments_suspended_at, 'mandat révoqué avec dette : suspendu immédiatement')
  await fw.recordIncident({ providerId: Q, kind: 'mandate_active', psp: 'test' })
  check(T.provider_profiles.find(x => x.id === Q).sepa_mandate_status === 'active', 'nouveau mandat signé : statut actif')
  console.log(`\n${ok} vérifications réussies, ${ko} échecs`)
})()
